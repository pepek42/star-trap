#!/usr/bin/env python3
"""Generate tool-specific agent and command files from the neutral sources in agents/.

Usage (from the repo root):
  scripts/sync-agents.py           write .claude/agents/*.md, .opencode/agent/*.md,
                                   .opencode/command/*.md
  scripts/sync-agents.py --check   exit 1 if any generated file is missing or stale

Source format (agents/<name>.md): frontmatter with
  name, description, color      copied through
  tier: cheap|standard|strong   model class; mapped per tool below
  effort: low|medium|high       optional, overrides the tier's default effort
  readonly: true|false          no file edits (Bash stays allowed for git/gradle)
  web: true|false               may use web search/fetch
followed by the prompt body, written tool-neutrally.

Claude Code gets a model alias + effort per tier. opencode gets no `model` line, so each
agent inherits the model picked in the session, unless agents/models.json maps the tier
to an opencode model id, e.g. {"opencode": {"cheap": "ollama/qwen3.5"}}.

Skills stay in .claude/skills/ (opencode reads that folder too); this script adds thin
opencode slash commands that load them.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "agents"
CLAUDE_DIR = ROOT / ".claude" / "agents"
OPENCODE_AGENT_DIR = ROOT / ".opencode" / "agent"
OPENCODE_CMD_DIR = ROOT / ".opencode" / "command"

CLAUDE_TIERS = {"cheap": ("haiku", "low"), "standard": ("sonnet", "medium"), "strong": ("opus", "high")}
SKILL_COMMANDS = {
    "auto-dev": "Run the auto-dev backlog loop",
    "plan-backlog": "Turn an idea or research doc into backlog cards",
}


def header(src_name):
    return f"<!-- Generated by scripts/sync-agents.py from agents/{src_name}. Edit the source, then rerun the script. -->\n"


def parse(path):
    text = path.read_text()
    if not text.startswith("---\n"):
        sys.exit(f"{path}: missing frontmatter")
    fm_text, body = text[4:].split("\n---\n", 1)
    fm = {}
    for line in fm_text.splitlines():
        if line.strip():
            key, _, value = line.partition(":")
            fm[key.strip()] = value.strip()
    for key in ("name", "description", "tier", "readonly", "web"):
        if key not in fm:
            sys.exit(f"{path}: frontmatter needs `{key}`")
    if fm["tier"] not in CLAUDE_TIERS:
        sys.exit(f"{path}: unknown tier {fm['tier']}")
    return fm, body.lstrip("\n")


def yaml_str(s):
    return json.dumps(s, ensure_ascii=False)


def claude_agent(fm, body, src_name):
    model, effort = CLAUDE_TIERS[fm["tier"]]
    effort = fm.get("effort", effort)
    readonly = fm["readonly"] == "true"
    tools = ["Read", "Bash", "Glob", "Grep"] if readonly else ["Read", "Edit", "Write", "Bash", "Glob", "Grep"]
    if fm["web"] == "true":
        tools += ["WebSearch", "WebFetch"]
    lines = [
        "---",
        f"name: {fm['name']}",
        f"description: {fm['description']}",
        f"tools: {', '.join(tools)}",
        f"model: {model}",
        f"effort: {effort}",
    ]
    if "color" in fm:
        lines.append(f"color: {fm['color']}")
    return "\n".join(lines) + "\n---\n\n" + header(src_name) + "\n" + body


def opencode_agent(fm, body, src_name, models):
    readonly = fm["readonly"] == "true"
    web = "allow" if fm["web"] == "true" else "deny"
    lines = [
        "---",
        f"description: {yaml_str(fm['description'])}",
        "mode: subagent",
    ]
    model = models.get("opencode", {}).get(fm["tier"])
    if model:
        lines.append(f"model: {model}")
    lines += [
        "permission:",
        f"  edit: {'deny' if readonly else 'allow'}",
        "  bash: allow",
        f"  webfetch: {web}",
        f"  websearch: {web}",
        "---",
    ]
    return "\n".join(lines) + "\n\n" + header(src_name) + "\n" + body


def opencode_command(skill, description):
    return (
        "---\n"
        f"description: {yaml_str(description)}\n"
        "---\n\n"
        f"<!-- Generated by scripts/sync-agents.py. The workflow lives in .claude/skills/{skill}/SKILL.md. -->\n\n"
        f"Load the `{skill}` skill (`.claude/skills/{skill}/SKILL.md`) and follow it. Arguments: $ARGUMENTS\n"
    )


def outputs():
    models_file = SRC / "models.json"
    models = json.loads(models_file.read_text()) if models_file.exists() else {}
    out = {}
    for path in sorted(SRC.glob("*.md")):
        fm, body = parse(path)
        out[CLAUDE_DIR / f"{fm['name']}.md"] = claude_agent(fm, body, path.name)
        out[OPENCODE_AGENT_DIR / f"{fm['name']}.md"] = opencode_agent(fm, body, path.name, models)
    for skill, description in SKILL_COMMANDS.items():
        out[OPENCODE_CMD_DIR / f"{skill}.md"] = opencode_command(skill, description)
    return out


def main():
    check = "--check" in sys.argv[1:]
    expected = outputs()
    stale = []
    for target, content in expected.items():
        if not target.exists() or target.read_text() != content:
            stale.append(target)
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content)
    # Generated agents whose source is gone.
    names = {p.name for p in expected if p.parent in (CLAUDE_DIR, OPENCODE_AGENT_DIR)}
    for folder in (CLAUDE_DIR, OPENCODE_AGENT_DIR):
        for p in folder.glob("*.md") if folder.exists() else []:
            if p.name not in names:
                stale.append(p)
                if not check:
                    p.unlink()
    rel = [str(p.relative_to(ROOT)) for p in stale]
    if check:
        if rel:
            print("STALE: " + ", ".join(rel) + " (run scripts/sync-agents.py)")
            sys.exit(1)
        print("OK")
    else:
        print("updated: " + (", ".join(rel) if rel else "nothing"))


if __name__ == "__main__":
    main()
